interface I18nContextType {
  lang: Langue;
  setLang: (l: Langue) => void;
  t: (cle: string) => string;
}

const I18nContext = createContext<I18nContextType>({
  lang: "fr",
  setLang: () => {},
  t: (cle: string) => DICO[cle]?.fr ?? cle,
});

export function useI18n() {
  return useContext(I18nContext);
}

// Langue courante hors React (pour les plugins/exécuteurs qui n'ont pas de hook).
// Même source que le provider (localStorage) → reste cohérent avec le toggle.
export function langueCourante(): Langue {
  try {
    if (typeof localStorage !== "undefined" && localStorage.getItem) {
      return (localStorage.getItem(LANG_KEY) as Langue) || "fr";
    }
  } catch { /* SSR/tests sans localStorage */ }
  return "fr";
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Langue>(
    () => {
      try {
        if (typeof localStorage !== "undefined" && localStorage.getItem) {
          return (localStorage.getItem(LANG_KEY) as Langue) || "fr";
        }
      } catch { /* SSR/tests */ }
      return "fr";
    }
  );

  const setLang = useCallback((l: Langue) => {
    setLangState(l);
    localStorage.setItem(LANG_KEY, l);
  }, []);

  const t = useCallback((cle: string) => {
    return DICO[cle]?.[lang] ?? cle;
  }, [lang]);

  return (
    <I18nContext.Provider value={{ lang, setLang, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export function traduire(cle: string, ...args: (string | number)[]): string {
  const lang = langueCourante();
  const s = DICO_RUNTIME[cle]?.[lang] ?? DICO_RUNTIME[cle]?.fr ?? DICO[cle]?.[lang] ?? DICO[cle]?.fr ?? cle;
  return s.replace(/\{__VAR_(\d+)__\}/g, (_, i) => {
    const idx = Number(i);
    return args.length > idx ? String(args[idx]) : `{__VAR_${idx}__}`;
  });
}

export function defautParametre(p: Pick<ParametreDef, "defaut" | "defautEn">, lang: Langue): string | number {
  return lang === "en" && p.defautEn !== undefined ? p.defautEn : p.defaut;
}
